using System.Text;
using System.Text.RegularExpressions;

namespace MutsumiLauncher.Services;

/// <summary>
/// 把订阅下发的 Clash YAML 改造成「只给启动器自己用」的最小配置：
/// 随机端口、只监听本机、丢掉机场那几千条规则、固定走指定节点。
/// 不做完整 YAML 解析——订阅里的 proxies 是流式写法，直接按行搬过来最稳。
/// </summary>
public static class ClashConfigBuilder
{
    /// <summary>机场订阅里的 ech-opts 配置，生成 Clash 配置时一律去掉。</summary>
    private static readonly Regex EchOptions = new(
        @",\s*ech-opts:\s*\{[^{}]*\}", RegexOptions.Compiled);

    private static readonly Regex NamePattern = new(
        @"^\s*-\s*(?:\{\s*)?name:\s*(?:'([^']*)'|""([^""]*)""|([^,}]+))",
        RegexOptions.Multiline);

    public static bool LooksLikeClash(string? yaml) =>
        !string.IsNullOrWhiteSpace(yaml)
        && (yaml.Contains("\nproxies:") || yaml.StartsWith("proxies:")
            || yaml.Contains("\nproxy-groups:"));

    /// <summary>取出 proxies 段原文（保留缩进），顺便读出所有节点名。</summary>
    public static (string Block, List<string> Names) ReadProxies(string yaml)
    {
        var lines = yaml.Replace("\r\n", "\n").Split('\n');
        var start = Array.FindIndex(lines, line => line.StartsWith("proxies:", StringComparison.Ordinal));
        if (start < 0) return (string.Empty, []);

        var end = start + 1;
        while (end < lines.Length)
        {
            var line = lines[end];
            if (line.Length > 0 && !char.IsWhiteSpace(line[0])) break;
            end++;
        }

        var block = string.Join('\n', lines[(start + 1)..end]).TrimEnd();
        var names = new List<string>();

        foreach (var line in lines[(start + 1)..end])
        {
            var match = NamePattern.Match(line);
            if (!match.Success) continue;

            var name = match.Groups[1].Value.Length > 0 ? match.Groups[1].Value
                : match.Groups[2].Value.Length > 0 ? match.Groups[2].Value
                : match.Groups[3].Value;

            name = name.Trim();
            if (name.Length > 0) names.Add(name);
        }

        return (block, names);
    }

    /// <summary>机场塞在节点列表里的「剩余流量 / 到期时间」这类展示项，不是真节点。</summary>
    private static readonly string[] InfoKeywords =
        ["剩余", "到期", "重置", "官网", "订阅", "有效期", "流量", "套餐", "客服"];

    public static bool IsInfoNode(string name)
        => InfoKeywords.Any(keyword => name.Contains(keyword, StringComparison.Ordinal));

    /// <summary>去掉信息节点；全被过滤掉时退回原列表（总比没有强）。</summary>
    public static List<string> RealNodes(IReadOnlyList<string> names)
    {
        var real = names.Where(name => !IsInfoNode(name)).ToList();
        return real.Count > 0 ? real : names.ToList();
    }

    /// <summary>按「包含匹配」挑节点；挑不到就用低倍率节点，再不行用第一个。</summary>
    public static string? PickNode(IReadOnlyList<string> names, string? preferred)
    {
        var candidates = RealNodes(names);
        if (candidates.Count == 0) return null;

        if (!string.IsNullOrWhiteSpace(preferred))
        {
            var hit = candidates.FirstOrDefault(name =>
                name.Contains(preferred.Trim(), StringComparison.OrdinalIgnoreCase));
            if (hit is not null) return hit;
        }

        return candidates.FirstOrDefault(name => name.Contains("0.1倍", StringComparison.Ordinal))
               ?? candidates.FirstOrDefault(name => name.Contains("X0.1", StringComparison.OrdinalIgnoreCase))
               ?? candidates[0];
    }

    /// <summary>生成最小配置；失败返回 null（调用方回落直连）。</summary>
    public static (string Yaml, string Node, int NodeCount)? Build(string subscriptionYaml,
        string? preferredNode, int port)
    {
        var (block, names) = ReadProxies(subscriptionYaml);
        if (block.Length == 0 || names.Count == 0) return null;

        // 机场给节点加了 ech-opts: { enable: true }，但 mihomo 解析 ECH 配置失败时
        // 整条连接会直接 "context deadline exceeded"，节点全废。
        // 实测去掉之后同一个订阅能跑到 10 MB/s。
        block = EchOptions.Replace(block, string.Empty);

        var node = PickNode(names, preferredNode);
        if (node is null) return null;

        // 首选节点打头，其余真实节点全部当备用：首选挂了 mihomo 自动往下找
        var real = RealNodes(names);
        var group = new List<string> { node };
        group.AddRange(real
            .Where(name => !name.Equals(node, StringComparison.Ordinal)));

        string Quote(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

        var builder = new StringBuilder();
        builder.AppendLine("# generated by Mutsumi Launcher");
        builder.AppendLine($"mixed-port: {port}");
        builder.AppendLine("allow-lan: false");
        builder.AppendLine("bind-address: '127.0.0.1'");
        builder.AppendLine("mode: rule");
        builder.AppendLine("log-level: warning");
        builder.AppendLine("ipv6: false");
        builder.AppendLine("unified-delay: true");
        builder.AppendLine("tcp-concurrent: true");
        builder.AppendLine("external-controller: ''");
        // GeoIP 数据库别从 GitHub 下（国内经常卡住），换成 jsDelivr
        builder.AppendLine("geodata-mode: true");
        builder.AppendLine("geo-auto-update: false");
        builder.AppendLine("geox-url:");
        builder.AppendLine("  mmdb: \"https://cdn.jsdelivr.net/gh/MetaCubeX/meta-rules-dat@release/country.mmdb\"");
        // 节点域名用 DoH 解析。节点域名（bgp.cn.xxx）在国内 DNS 上经常被污染成
        // Cloudflare 的 IP，连过去拿到的是 cloudflare-ech.com 的证书，TLS 校验必挂。
        // 所以优先用 Cloudflare 自己的 DoH 解析节点域名。
        // DNS 配置照抄实测能跑满速的那份（Clash Party 生成的）：
        // fake-ip + 国内 DoH + fallback，缺一不可——之前的简化版会导致
        // 节点域名解析被污染，拨号直接 i/o timeout。
        builder.AppendLine("dns:");
        builder.AppendLine("  enable: true");
        builder.AppendLine("  ipv6: false");
        builder.AppendLine("  use-hosts: true");
        builder.AppendLine("  enhanced-mode: fake-ip");
        builder.AppendLine("  fake-ip-range: 198.18.0.1/16");
        builder.AppendLine("  default-nameserver: [119.29.29.29, 223.5.5.5, 180.76.76.76]");
        builder.AppendLine("  nameserver: ['https://doh.pub/dns-query', 'https://dns.alidns.com/dns-query', 'tls://dns.alidns.com:853', 'tls://dot.pub:853']");
        builder.AppendLine("  fallback: ['https://dns.alidns.com/dns-query', 'https://doh.pub/dns-query']");
        builder.AppendLine("  fake-ip-filter: ['*.lan', '*.local', '*.localhost', '*.test', '+.stun.*.*']");
        builder.AppendLine("  fallback-filter: { geoip: true, geoip-code: CN, ipcidr: [240.0.0.0/4, 0.0.0.0/32] }");
        builder.AppendLine("proxies:");
        builder.AppendLine(block);
        builder.AppendLine("proxy-groups:");
        // 1) 普通请求：延迟最低的节点
        builder.AppendLine("  - name: mtl-auto");
        builder.AppendLine("    type: url-test");
        builder.AppendLine("    url: https://www.gstatic.com/generate_204");
        builder.AppendLine("    interval: 120");
        builder.AppendLine("    tolerance: 100");
        builder.AppendLine("    lazy: false");
        builder.AppendLine("    proxies:");
        foreach (var name in group) builder.AppendLine($"      - {Quote(name)}");

        // 2) 文件下载：轮询分摊到所有健康节点
        //    单节点带宽有限，而且机场节点经常个别掉线，8 条分段全挤在一个节点上必然互相拖累。
        builder.AppendLine("  - name: mtl-balance");
        builder.AppendLine("    type: load-balance");
        builder.AppendLine("    strategy: round-robin");
        builder.AppendLine("    url: https://www.gstatic.com/generate_204");
        builder.AppendLine("    interval: 60");
        builder.AppendLine("    lazy: false");
        builder.AppendLine("    proxies:");
        foreach (var name in group) builder.AppendLine($"      - {Quote(name)}");

        builder.AppendLine("rules:");
        // 大文件走负载均衡组：每个连接落到不同节点，互不抢占
        builder.AppendLine("  - \"DOMAIN-SUFFIX,cdn.modrinth.com,mtl-balance\"");
        builder.AppendLine("  - \"DOMAIN-SUFFIX,forgecdn.net,mtl-balance\"");
        builder.AppendLine("  - \"DOMAIN-SUFFIX,overwolf.wtf,mtl-balance\"");
        builder.AppendLine("  - \"MATCH,mtl-auto\"");

        return (builder.ToString(), node, real.Count);
    }
}